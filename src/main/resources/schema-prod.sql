-- Tablas del perfil PROD. Con ddl-auto=validate Hibernate no crea tablas, solo comprueba que existen.
CREATE TABLE IF NOT EXISTS peliculas (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo              VARCHAR(150) NOT NULL UNIQUE,
    duracion            INTEGER NOT NULL,
    genero              ENUM ('ACCION','ANIMADA','CIENCIA_FICCION','COMEDIA','DRAMA','TERROR') NOT NULL,
    fecha_estreno       DATE NOT NULL,
    clasificacion       FLOAT(53),
    idioma              VARCHAR(2) NOT NULL,
    email_distribuidora VARCHAR(100) NOT NULL,
    disponible          BOOLEAN NOT NULL
);

CREATE TABLE IF NOT EXISTS pelicula_etiquetas (
    pelicula_id BIGINT NOT NULL REFERENCES peliculas (id),
    etiqueta    VARCHAR(30)
);
